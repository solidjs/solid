/**
 * Emits an async-gen scenario as a TSX module, so one app compiles for the
 * server (renderToStream) and for the client (hydrate, render) through the
 * real JSX transform, with its templates, hydration keys and grouped effects.
 *
 * The module exports `createApp(ctx)`. Every async memo asks through
 * `ctx.ask(name, v, poison)`, which the caller implements per mode: a timed
 * promise on the server, a manual flight on the client (counted as an ask
 * only when it is a real Promise — hydration's dry run fakes the global), a
 * synchronous value or throw for the fresh render.
 */
import type { Node, Read, Scenario, SrcRef } from "./scenario.js";

export interface AppContext {
  values: number[];
  ask(name: string, v: number, poison: number | null): unknown;
}

const ref = (r: SrcRef) => (r.k === "s" ? `S[${r.i}][0]` : `M[${r.i}]`);
const name = (r: SrcRef) => `${r.k}${r.i}`;
const prefix = { plain: "v", latest: "l", pending: "p" } as const;

function readExpr(r: Read): string {
  return r.how === "plain"
    ? `${ref(r.src)}()`
    : r.how === "latest"
      ? `latest(${ref(r.src)})`
      : `isPending(${ref(r.src)})`;
}
const textExpr = (r: Read) => `T("${prefix[r.how]}${name(r.src)}", () => ${readExpr(r)})`;

function node(n: Node): string {
  switch (n.t) {
    case "loading":
      return `<Loading fallback="[L]">${node(n.child)}</Loading>`;
    case "errored":
      return `<Errored fallback={(e: unknown) => "[E]"}>${node(n.child)}</Errored>`;
    case "show":
      return `<Show when={${readExpr(n.when)}}${n.fallback ? ` fallback="[F]"` : ""}>${node(n.child)}</Show>`;
    case "group":
      return `<>${n.kids.map(node).join("")}</>`;
    case "leaf": {
      const attrs = n.attrs.map((r, j) => ` data-a${j}={${textExpr(r)}}`).join("");
      return `<span${attrs}>${n.text.map(r => `{${textExpr(r)}}`).join("")}</span>`;
    }
  }
}

export function emitApp(sc: Scenario): string {
  const memos = sc.memos
    .map((m, i) => {
      const input = m.deps
        .map(d =>
          d.how === "latest" ? `Number(latest(${ref(d.src)}))` : `Number(${ref(d.src)}())`
        )
        .join(" + ");
      const poison = m.poison === null ? "null" : String(m.poison);
      return m.async
        ? `  M[${i}] = createMemo(() => { const v = 1 + ${input}; return ctx.ask("m${i}", v, ${poison}); });`
        : `  M[${i}] = createMemo(() => { const v = 1 + ${input}; if (${poison} !== null && v % 4 === ${poison}) throw new Error("m${i}:" + v); return v; });`;
    })
    .join("\n");
  return `/**
 * @jsxImportSource @solidjs/web
 * Generated by test/async-gen/emit.ts — do not edit.
 */
import { Errored, Loading, Show, createMemo, createSignal, isPending, latest } from "solid-js";
import type { AppContext } from "../emit.js";

const T = (label: string, read: () => unknown) => label + ":" + String(read()) + " ";

export function createApp(ctx: AppContext) {
  const S = ctx.values.map(v => createSignal(v, { ownedWrite: true }));
  function App() {
    const M: (() => any)[] = [];
${memos}
    return (
      <main>
        <Errored fallback={(e: unknown) => "[ROOT-E]"}>
          <Loading fallback="[ROOT-L]">${node(sc.tree)}</Loading>
        </Errored>
      </main>
    );
  }
  return { App, S };
}
`;
}
